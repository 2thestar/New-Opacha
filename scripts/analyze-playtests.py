"""Summarize real-simulation CSVs; keep losses and time limits in the denominator."""
import csv
import hashlib
import json
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LABELS = {"conquest": "Conquest", "capture_flag": "Neutral flag", "home_flags": "Starting flags", "alliances": "Alliances"}


def read(name):
    path = ROOT / "docs/playtests" / name
    with path.open(newline="", encoding="utf-8") as stream:
        rows = list(csv.DictReader(stream))
    return rows, hashlib.sha256(path.read_bytes()).hexdigest()


def median(rows, field, wins=False):
    values = [float(row[field]) for row in rows if float(row[field]) >= 0 and (not wins or row["won"] == "true")]
    return f"{statistics.median(values):.1f}" if values else "—"


def wins(rows):
    return sum(row["won"] == "true" for row in rows)


def main():
    campaign, campaign_hash = read("campaign.csv")
    random, random_hash = read("random.csv")
    holdout, holdout_hash = read("holdout.csv")
    levels = json.loads((ROOT / "assets/campaign/levels.json").read_text(encoding="utf-8"))["levels"]
    lines = ["# Simulation results", "", "Generated by `scripts/analyze-playtests.py`. Times are game seconds at 1×, not wall-clock minutes. A win rate describes these scripted policies, not a human difficulty rating.", "", "## Campaign", "", "| Mode | Matches | Wins | Median winning duration | Median first capture | Reached 300 s limit |", "| --- | ---: | ---: | ---: | ---: | ---: |"]
    for mode, label in LABELS.items():
        group = [row for row in campaign if row["mode"] == mode]
        lines.append(f"| {label} | {len(group)} | {wins(group)} | {median(group,'seconds',True)} | {median(group,'first_capture')} | {sum(float(r['seconds'])>=299.9 for r in group)} |")
    lines += ["", "Seven policies, two decision-error seeds per map. Each policy has one order opportunity every 1.2–2 seconds, or 3.5–4.3 for hesitant play. Planner can queue two orders at a decision, representing tactical pause. Upgrade and weapon choices also consume an opportunity. AI uses the authored difficulty and visible starting garrisons; adaptive difficulty is disabled.", "", "| Policy | Campaign wins / 96 | Tool actions | Pact actions |", "| --- | ---: | ---: | ---: |"]
    for style in dict.fromkeys(row["style"] for row in campaign):
        group = [row for row in campaign if row["style"] == style]
        lines.append(f"| {style} | {wins(group)} | {sum(int(r['tools']) for r in group)} | {sum(int(r['pacts']) for r in group)} |")
    lines += ["", "## Authored map coverage", "", "Winning policies are evidence of an available line, not required solutions. Repeated captures include retaking lost nodes.", "", "| Map | Title | Wins / 14 | Winning policies | Median winning duration |", "| ---: | --- | ---: | --- | ---: |"]
    for level in levels:
        group = [row for row in campaign if int(row["level"]) == level["index"]+1]
        styles = sorted({row["style"] for row in group if row["won"] == "true"})
        lines.append(f"| {level['index']+1} | {level['title']} | {wins(group)} | {', '.join(styles) or 'NONE'} | {median(group,'seconds',True)} |")
    lines += ["", "## Random skirmish stress test", "", "Four map seeds, green/red starting-position swaps, seven policies, hard difficulty, all tools enabled. These are deliberately harder than the opening campaign; tiny random maps can put opponents close together.", "", "| Mode | Matches | Wins | Median winning duration | Median first capture | Reached 300 s limit |", "| --- | ---: | ---: | ---: | ---: | ---: |"]
    for mode, label in LABELS.items():
        group = [row for row in random if row["mode"] == mode]
        lines.append(f"| {label} | {len(group)} | {wins(group)} | {median(group,'seconds',True)} | {median(group,'first_capture')} | {sum(float(r['seconds'])>=299.9 for r in group)} |")
    lines += ["", "## Additional error seeds", "", "Maps 19, 21 and 48 had narrow winning-policy coverage. Seeds 3–6 were held out from the tuning sweep. Each had at least one winning policy on every additional seed.", "", "| Map | Matches | Wins | Winning policies |", "| ---: | ---: | ---: | --- |"]
    for level in (19,21,48):
        group = [row for row in holdout if int(row['level'])==level]
        styles = sorted({row['style'] for row in group if row['won']=='true'})
        lines.append(f"| {level} | {len(group)} | {wins(group)} | {', '.join(styles)} |")
    lines += ["", "## Reproduction", "", "```powershell", r".\opacha.ps1 :lwjgl3:balancePlaytest -PcampaignLab -PlabName=campaign", r".\opacha.ps1 :lwjgl3:balancePlaytest -PlabName=random", r".\opacha.ps1 :lwjgl3:balancePlaytest -PcampaignLab -PlabName=holdout '-PlabLevels=19,21,48' -PlabSeedStart=3 -PlabSeeds=4", "```", "", "A match stops at a mode winner, human elimination, or 300 game seconds. `winner=null` before 300 seconds means human elimination before the remaining AI decided the winner; it is not a timeout. Capture counts are sampled every half game second and can miss a very fast capture/recapture between samples. All match rows, including failures, remain in the CSVs.", "", f"Campaign CSV SHA256: `{campaign_hash}`.", "", f"Random CSV SHA256: `{random_hash}`.", "", f"Holdout CSV SHA256: `{holdout_hash}`."]
    (ROOT / "docs/balance-metrics.md").write_text("\n".join(lines)+"\n", encoding="utf-8")


if __name__ == "__main__":
    main()
